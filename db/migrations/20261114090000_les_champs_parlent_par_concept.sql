-- Les champs parlent par concept : le dictionnaire qui relie les 2 133 champs.
--
-- POURQUOI. Les 77 grilles de `20261105110000` nomment 1539 codes de champ différents
-- pour des notions souvent identiques : `raison_sociale_emetteur`, `nom_client`,
-- `employeur_raison_sociale` et `tireur_nom` sont tous une raison sociale ;
-- `matricule_fiscal_emetteur`, `client_mf` et `payeur_matricule` sont tous un
-- matricule fiscal. Sans ce lien, un expert ne vaut que pour UN champ, et le
-- moteur qui naît de la base devrait en générer deux mille. Avec lui, l'expert
-- du matricule fiscal lit les 50 champs qui en portent un.
--
-- CE QUE FAIT CETTE MIGRATION.
--   1. `ref.concepts` : la notion (code, libellé) et son EXPERT, l'un des six
--      lecteurs génériques — montant, identifiant, date, reference, tiers,
--      libelle. Rattachée au pack tunisien en cours, datée en littéral (R11),
--      livrée en défaut (`defaut_a_valider`, R10).
--   2. `ref.grille_champs` gagne `concept_id` (la notion) et `role` (à qui elle
--      appartient sur la pièce : émetteur, client, salarié, banque...). Un
--      champ garde son code, son type et ses repères : rien n'est renommé.
--   3. Le semis : 1254 concepts ; 225 sont partagés par plusieurs champs et
--      couvrent 1104 champs ; les autres sont propres à un seul champ (une ligne
--      du bilan n'a pas de jumelle). Par expert : date 201, identifiant 195, libelle 735, montant 656, reference 104, tiers 242.
--   4. Une garde : aucun champ ne reste sans concept.
--
-- COMMENT LE LIEN EST FAIT. Par règles déterministes, sans modèle : le jeton de
-- rôle est retiré du code (`_emetteur`, `employeur_`, `compte_titulaire_`...),
-- le reste est cherché dans une table de synonymes revue champ par champ. Un
-- champ dont le type ne convient pas à l'expert du concept (une clause de
-- pénalités écrite en texte n'est pas un montant) garde un concept à lui.
-- C'est un DÉFAUT : l'expertise peut le corriger sans migration (R10).

-- ============================================================ 1. LE DICTIONNAIRE

create table if not exists ref.concepts (
  id               uuid primary key default gen_random_uuid(),
  pack_version_id  uuid not null references ref.jurisdiction_packs(id) on delete cascade,
  code             text not null check (code ~ '^[a-z][a-z0-9_]*$'),
  libelle          text not null,
  -- Le lecteur générique qui lit et vérifie ce concept.
  expert           text not null check (expert in ('montant', 'identifiant', 'date', 'reference',
                                                   'tiers', 'libelle')),
  statut           text not null check (statut in ('defaut_a_valider', 'arrete')),
  valid_from       date not null,
  valid_to         date check (valid_to is null or valid_to >= valid_from),
  unique (pack_version_id, code, valid_from)
);

comment on table ref.concepts is
  'Le dictionnaire des concepts : une notion partagée par les champs de plusieurs grilles, '
  'et l''expert générique qui la lit. Défaut livré par Malica (R10).';

alter table ref.concepts enable row level security;
alter table ref.concepts force row level security;
revoke all on table ref.concepts from public, anon, service_role;
grant select on table ref.concepts to authenticated;
drop policy if exists ref_concepts_sel on ref.concepts;
create policy ref_concepts_sel on ref.concepts for select to authenticated using (true);

create index if not exists concepts_pack_idx on ref.concepts (pack_version_id, code);

-- ============================================= 2. LE CHAMP DIT SON CONCEPT ET SON RÔLE

alter table ref.grille_champs
  add column if not exists concept_id uuid references ref.concepts(id),
  add column if not exists role text check (role is null or role ~ '^[a-z][a-z_]*$');

create index if not exists grille_champs_concept_id_fk_idx on ref.grille_champs (concept_id);

comment on column ref.grille_champs.concept_id is
  'La notion que porte ce champ (dictionnaire `ref.concepts`) : deux champs du même concept '
  'sont lus par le même expert.';
comment on column ref.grille_champs.role is
  'À qui appartient la notion sur la pièce (emetteur, client, salarie, banque...). Nul : la pièce elle-même.';

create or replace view public.ref_concepts_v with (security_invoker = true) as
  select id, pack_version_id, code, libelle, expert, statut, valid_from, valid_to
    from ref.concepts;

-- Ajoutées À LA FIN : `create or replace view` refuse tout autre changement.
