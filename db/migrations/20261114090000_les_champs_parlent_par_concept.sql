do $$
declare
  v_orph text;
begin
  select string_agg(g.code || '/' || c.code, ', ') into v_orph
    from ref.grille_champs c join ref.grilles g on g.id = c.grille_id
   where c.concept_id is null;
  if v_orph is not null then
    raise exception 'champs sans concept : %', v_orph;
  end if;

  select string_agg(k.code, ', ') into v_orph
    from ref.concepts k
   where not exists (select 1 from ref.grille_champs c where c.concept_id = k.id);
  if v_orph is not null then
    raise exception 'concepts sans champ : %', v_orph;
  end if;
end $$;
